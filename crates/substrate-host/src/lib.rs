    async fn destroy_workspace(
        &self,
        workspace_id: &str,
        root_name: &str,
    ) -> Result<WorkspaceDestroyProgress, DriverError> {
        let workspace_id = workspace_id.to_owned();
        let root_name = root_name.to_owned();
        let quota_path = self.config.workspace_root.join(&root_name);
        let quotas = self.quotas.clone();
        let workspace_destroy_namespace = self.workspace_destroy_namespace;
        let git_baseline_root =
            (!self.config.git_sources.is_empty()).then(|| self.config.git_baseline_root());
        self.filesystem_io(move |filesystem| {
            let _ownership =
                WorkspaceDestroyOwnership::acquire(workspace_destroy_namespace, &root_name)?;
            match filesystem.destroy_workspace_batch(&root_name)? {
                fs::WorkspaceDestroyBatch::Pending { removed_items } => {
                    Ok(WorkspaceDestroyProgress::Pending { removed_items })
                }
                fs::WorkspaceDestroyBatch::Absent => {
                    if let Some(baseline_root) = git_baseline_root.as_ref() {
                        git::remove_baseline(baseline_root, &root_name)?;
                    }
                    if let Some(quotas) = quotas.as_ref() {
                        quotas.release(&quota_path)?;
                    }
                    Ok(WorkspaceDestroyProgress::Absent(WorkspaceAbsence {
                        kind: substrate_wire::WorkspaceKind::Workspace,
                        id: workspace_id,
                        absent: true,
                        observed_at: Utc::now(),
                    }))
                }
            }
        })
        .await
    }

    async fn forget_workspace(
        &self,
        workspace_id: &str,
        root_name: &str,
    ) -> Result<WorkspaceAbsence, DriverError> {
        fs::validate_root_name(root_name)?;
        // The baseline is the daemon's, made beside the directory and never in it; it goes
        // whatever the current Git source configuration, because an earlier one may have written
        // it. The operator's directory is not opened at all.
        let baseline_root = self.config.git_baseline_root();
        let root_name = root_name.to_owned();
        self.filesystem_io(move |_| git::remove_baseline(&baseline_root, &root_name))
            .await?;
        Ok(WorkspaceAbsence {
            kind: substrate_wire::WorkspaceKind::Workspace,
            id: workspace_id.to_owned(),
            absent: true,
            observed_at: Utc::now(),
        })
    }

